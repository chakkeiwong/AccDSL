"""Closed residual types; quantities are rational, never implicit floats."""
def extend(g):
    obj,arr,enum,maybe,Q,ID,INT,BOOL,DATE = (g[k] for k in ('obj','arr','enum','maybe','Q','ID','INT','BOOL','DATE'))
    def qs(*names): return {k:Q for k in names}
    components={
      'debt':obj({'instrument_id':ID,'originated':BOOL,'rate_mode':enum('exact','enclosure'),
        **qs('principal','legal_interest','carrying','rate','rate_low','rate_high','term_years','elapsed_years'),
        'issue_date':DATE,'due_date':DATE,'defaulted':BOOL}),
      'modification':obj({'instrument_id':ID,**qs('carrying','old_rate','old_payment','new_payment','new_rate','principal_basis','test_ratio'),
        'due_date':DATE,'phase':enum('original','modified','accrued','paid'),'outcome':enum('none','substantial','non_substantial')}),
      'shares':obj({'class_id':ID,**qs('issued','treasury','treasury_cost','capital','surplus')}),
      'compound':obj({'instrument_id':ID,'phase':enum('unissued','issued','matured','ended'),
        **qs('debt','debt_cash_basis','original_equity','redemption','fixed_shares','rate','capital','retained_debit'),
        'due_date':DATE,'valuation_mode':enum('exact','source_rounded'),
        **qs('coupon','periods','old_period_rate','current_period_rate')}),
      'vesting':obj({'grant_id':ID,'condition':enum('service','non_market','market'),
        **qs('employees','awards_each','grant_fv','award_equity','cost'),
        'years':INT,'elapsed':INT,'service_dates':arr(DATE,1),'cancelled':BOOL,'paid':BOOL}),
      'cashaward':obj({'grant_id':ID,**qs('employees','awards_each','liability','cost','last_fv'),
        'years':INT,'elapsed':INT,'service_dates':arr(DATE,1),'paid':BOOL}),
      'choice':obj({'grant_id':ID,'holder':enum('counterparty','entity'),
        'classification':enum('unassessed','compound','cash','equity'),
        **qs('liability','equity','cost'),'granted':BOOL,'settled':BOOL,'services_complete':BOOL,
        'liability_valuation_date':maybe(DATE)}),
      'eps':obj({'period_start':DATE,'period_end_exclusive':DATE,
        'intervals':arr(obj({'start':DATE,'end_exclusive':DATE,'ordinary_shares':Q}),1),
        'rights':enum('plain','uncapped_weighted'),'rights_known':BOOL,'other_instruments_absent':BOOL,
        **qs('profit','continuing_profit','ordinary_dividends','participant_dividends','participants','participation_weight',
          'option_quantity','strike','future_service','choice_shares','choice_expense','choice_continuing_expense'),
        'average_price':maybe(Q),'after_tax_adjustment_known':BOOL,'computed':BOOL,
        **qs('numerator','denominator','diluted_numerator','diluted_denominator','participant_earnings','participant_eps')}),
      'fvhedge':obj({'designation_id':ID,**qs('principal','coupon','debt','derivative','basis','revised_rate','contractual_accrual'),
        'due_date':DATE,'active':BOOL,'measured':BOOL,'accrued':BOOL,'paid':BOOL,'settled':BOOL}),
      'reform':obj({'designation_id':ID,**qs('principal','old_coupon','new_benchmark','spread','reserve'),
        'qualified':BOOL,'amended':BOOL,'active':BOOL,'change_date':DATE,'reporting_end':DATE}),
    }
    events={
      'debt.issue':obj({'proceeds':Q,'rate':Q}),
      'debt.fee':obj({'amount':Q,'directly_attributable':BOOL,'rate_low':Q,'rate_high':Q}),
      'debt.accrue':obj({'year_fraction':Q,'factor':Q}),
      'debt.pay':obj({'principal':Q,'interest':Q,'legal_release_of_unpaid':BOOL}),
      'modification.change':obj({'new_payment':Q,'lender_fee':Q,'third_party_fee':Q,'fee_scope_known':BOOL,
        'qualitative':enum('substantial','non_substantial','unknown'),'replacement_fv':maybe(Q)}),
      'modification.accrue':obj({'rate':Q}),
      'modification.pay':obj({'amount':Q}),
      'shares.issue':obj({'quantity':Q,'price':Q}),
      'shares.buy':obj({'quantity':Q,'price':Q}),
      'shares.reissue':obj({'quantity':Q,'price':Q}),
      'compound.issue':obj({'proceeds':Q,'debt_fv':maybe(Q),'fixed_for_fixed':BOOL}),
      'compound.accrue':obj({'rate':Q}),
      'compound.end':obj({'route':enum('redeem','convert'),'amount_or_shares':Q,'original_rights_unchanged':BOOL}),
      'compound.repurchase':obj({'consideration':Q,'unchanged_rights':BOOL,'comparable_debt_rate_known':BOOL}),
      'vesting.service':obj({'elapsed':INT,'employees':Q,'other_conditions_met':BOOL,'market_met':BOOL}),
      'vesting.fail':obj({'non_market_failure':BOOL}),
      'vesting.cancel':obj({'replacement':BOOL}),
      'vesting.pay':obj({'amount':Q,'award_fv':maybe(Q)}),
      'cashaward.service':obj({'elapsed':INT,'employees':Q,'fv':maybe(Q)}),
      'cashaward.settle':obj({'fv':maybe(Q),'amount':Q}),
      'choice.grant':obj({'cash_fv':maybe(Q),'share_fv':maybe(Q),'practice_cash':maybe(BOOL),
        'policy_cash':maybe(BOOL),'equity_lacks_substance':maybe(BOOL)}),
      'choice.remeasure':obj({'liability_fv':maybe(Q)}),
      'choice.settle':obj({'route':enum('cash','shares'),'cash_paid':Q,'shares_fv':maybe(Q),'cash_alternative_fv':maybe(Q)}),
      **{k:obj({'full_period_rights':BOOL}) for k in ['eps.basic','eps.options','eps.choice','eps.participation']},
      'fvhedge.measure':obj({'derivative_gain':maybe(Q),'risk_debt_loss':maybe(Q),'eligibility_known':BOOL}),
      'fvhedge.discontinue':obj({'revised_rate':Q,'final_measurement_done':BOOL}),
      'fvhedge.accrue':obj({'rate':Q}),
      'fvhedge.pay':obj({'amount':Q}),
      'fvhedge.settle':obj({'amount':Q}),
      'reform.assess':obj({'direct_cause':maybe(BOOL),'economically_equivalent':maybe(BOOL),
        'additional_changes':enum('none','unassessed','separate_method_required'),'derecognition_assessed':BOOL}),
      'reform.amend':obj({'documented':BOOL,'same_relationship':BOOL}),
    }
    g['COMPONENTS'].update(components)
    g['EVENTS'].update({k:(k.split('.')[0],v) for k,v in events.items()})
    g['EQUITY'] += ['treasury','share_surplus']
    g['ACCOUNTS'] += ['treasury','share_surplus']
    g['EQUITY_MOVEMENTS'] += ['repurchase','reissue']
    g['EPS_QUANTITY']=obj({'currency':enum('USD'),'unit':enum('currency_per_ordinary_share'),
      'period_start':DATE,'period_end_exclusive':DATE,
      **qs('ordinary_earnings','weighted_ordinary_shares','basic','diluted_earnings','diluted_shares','diluted',
        'participant_earnings','participant_eps')})
